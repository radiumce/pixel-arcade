// A tiny original NROM cycles the universal background palette every vblank.
// No commercial game or downloaded ROM is needed for the transport regression.
const rom = Buffer.alloc(16 + 16384 + 8192);
Buffer.from([0x4e, 0x45, 0x53, 0x1a, 1, 1]).copy(rom);
const program = [0x78,0xd8,0xa2,0xff,0x9a,0xe8,0x8e,0,0x20,0x8e,1,0x20,
  0x2c,2,0x20,0x10,0xfb,0xa9,0x3f,0x8d,6,0x20,0xa9,0,0x8d,6,0x20,
  0xa5,0,0x29,0x3f,0x8d,7,0x20,
  // Reset PPUADDR outside palette RAM so disabled rendering shows palette[0].
  0xa9,0,0x8d,6,0x20,0x8d,6,0x20,0xe6,0,0x4c,0x0c,0x80];
Buffer.from(program).copy(rom, 16);
for (const offset of [0x3ffa, 0x3ffc, 0x3ffe]) rom.writeUInt16LE(0x8000, 16 + offset);

// Pixel-detail probe: a full-screen 1-pixel checkerboard (black / colour 1).
// Its NMI toggles colour 1 between white ($30) and red ($16) on every frame,
// like games that multiplex sprites on alternate frames. Any resampling error
// breaks the checkerboard; any dropped or duplicated frame breaks the toggle.
const detailRom = Buffer.alloc(16 + 16384 + 8192);
Buffer.from([0x4e, 0x45, 0x53, 0x1a, 1, 1]).copy(detailRom);
const detailProgram = [
  0x78, 0xd8, 0xa2, 0xff, 0x9a, 0xe8, 0x8e, 0x00, 0x20, 0x8e, 0x01, 0x20, // $8000 init
  0x2c, 0x02, 0x20, 0x10, 0xfb, 0x2c, 0x02, 0x20, 0x10, 0xfb,             // $800C wait 2 vblanks
  0xa9, 0x3f, 0x8d, 0x06, 0x20, 0xa9, 0x00, 0x8d, 0x06, 0x20,             // $8016 PPUADDR=$3F00
  0xa9, 0x0f, 0x8d, 0x07, 0x20, 0xa9, 0x30, 0x8d, 0x07, 0x20,             // $8020 black, white
  0xa9, 0x20, 0x8d, 0x06, 0x20, 0xa9, 0x00, 0x8d, 0x06, 0x20,             // $802A PPUADDR=$2000
  0xa2, 0x04, 0xa0, 0x00, 0x8d, 0x07, 0x20, 0xc8, 0xd0, 0xfa, 0xca, 0xd0, 0xf7, // $8034 1 KiB of tile 0
  0x8d, 0x05, 0x20, 0x8d, 0x05, 0x20,                                     // $8041 scroll 0,0
  0xa9, 0x80, 0x8d, 0x00, 0x20, 0xa9, 0x0a, 0x8d, 0x01, 0x20,             // $8047 NMI on, BG on
  0x4c, 0x51, 0x80,                                                       // $8051 idle
  0x48, 0x8a, 0x48,                                                       // $8054 NMI: save A, X
  0xa9, 0x3f, 0x8d, 0x06, 0x20, 0xa9, 0x01, 0x8d, 0x06, 0x20,             // PPUADDR=$3F01
  0xa5, 0x00, 0x49, 0x01, 0x85, 0x00, 0xaa, 0xbd, 0x80, 0x80, 0x8d, 0x07, 0x20, // toggle colour
  0xa9, 0x00, 0x8d, 0x06, 0x20, 0x8d, 0x06, 0x20, 0x8d, 0x05, 0x20, 0x8d, 0x05, 0x20,
  0x4c, 0x84, 0x80, 0xea,                                                 // skip table
  0x30, 0x16, 0xea, 0xea,                                                 // $8080 colours
  0xa9, 0x80, 0x8d, 0x00, 0x20, 0x68, 0xaa, 0x68, 0x40,                   // $8084 restore, RTI
];
Buffer.from(detailProgram).copy(detailRom, 16);
detailRom.writeUInt16LE(0x8054, 16 + 0x3ffa);
// A steady pulse also exercises audio capture and standalone guest playback.
// Keep the video/NMI addresses intact by using unused PRG space for reset setup.
Buffer.from([
  0x78, 0xa9, 0x01, 0x8d, 0x15, 0x40, // enable pulse 1
  0xa9, 0xbf, 0x8d, 0x00, 0x40,       // constant volume, length halt, 50% duty
  0xa9, 0x00, 0x8d, 0x01, 0x40,       // disable sweep
  0xa9, 0xfd, 0x8d, 0x02, 0x40,       // ~440 Hz timer
  0xa9, 0x08, 0x8d, 0x03, 0x40,
  0x4c, 0x00, 0x80,
]).copy(detailRom, 16 + 0x100);
detailRom.writeUInt16LE(0x8100, 16 + 0x3ffc);
detailRom.writeUInt16LE(0x8000, 16 + 0x3ffe);
// CHR tile 0: plane 0 alternates 10101010 / 01010101, plane 1 is empty.
for (let row = 0; row < 8; row++) detailRom[16 + 16384 + row] = row % 2 ? 0x55 : 0xaa;

export { rom, detailRom };
